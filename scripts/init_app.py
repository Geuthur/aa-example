#!/usr/bin/env python3
"""Create a new Alliance Auth app from this template.

The script renames the template package, the repository name and the verbose
name in every text file and path of the repository. The current names are read
from ``.make/config.ini`` (``[General]``: ``package``, ``appname`` and
``appname_verbose``); the title (``Example``), the settings prefix
(``EXAMPLE``) and the user agent (``AA-Example``) are derived from them, for
the template as well as for the new app.

    python3 scripts/init_app.py --package ledger --app-name aa-ledger \
        --verbose-name "AA Ledger" [--drop-migrations] \
        [--drop-template-override] [--dry-run]

Only the Python standard library is used. The script does not delete itself:
it stays in ``scripts/`` so a run can be repeated on a fresh copy.
"""

# Standard Library
import argparse
import ast
import configparser
import keyword
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from fnmatch import fnmatch
from pathlib import Path

NEW_VERSION = "0.1.0"
CONFIG_FILE = Path(".make") / "config.ini"

# Names that are never read or renamed, at any depth (``.git`` is a file in a
# git worktree, the others are directories).
SKIP_DIRS = {
    ".git",
    ".tox",
    ".venv",
    "venv",
    "node_modules",
    "htmlcov",
    "__pycache__",
    "build",
    "dist",
}
# Files that are never changed: source maps of the built frontend (they are
# regenerated by ``make react-build``) and the downloaded ESI specification
# (``openapi_<date>.json``, which uses ``example`` as an OpenAPI keyword).
# Files that git ignores (local configuration, caches, builds) are skipped too.
SKIP_FILE_PATTERNS = ("*.map", "openapi_*.json")
# Prose files: only the compound names (``AA Example``, ``aa-example``,
# ``AA-Example``) are replaced, never the bare words (``For example, ...``).
COMPOUND_ONLY_FILES = {"LICENSE"}
# Domains such as ``example.com`` stay as they are.
PROTECTED_DOMAINS = ("com", "org", "net")


class InitAppError(Exception):
    """A problem with the arguments or the repository."""


@dataclass(frozen=True)
class Names:
    """The three names of an app and the names derived from them."""

    package: str
    app_name: str
    verbose_name: str

    @property
    def title(self) -> str:
        return title_from_verbose(self.verbose_name)

    @property
    def settings_prefix(self) -> str:
        return self.package.upper()

    @property
    def user_agent(self) -> str:
        return f"AA-{self.title}"

    def validate(self) -> None:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", self.package) or keyword.iskeyword(
            self.package
        ):
            raise InitAppError(
                f"Package name {self.package!r} must be a lower case Python "
                "identifier (letters, digits, underscores)."
            )
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", self.app_name):
            raise InitAppError(
                f"App name {self.app_name!r} must be lower case letters, digits "
                "and hyphens, e.g. aa-ledger."
            )
        if not self.title:
            raise InitAppError(
                f"Verbose name {self.verbose_name!r} must contain a name "
                'besides "AA", e.g. "AA Ledger".'
            )


def title_from_verbose(verbose_name: str) -> str:
    """Derive the title from the verbose name: ``AA Voices of War`` -> ``VoicesOfWar``."""
    words = [word for word in re.split(r"[^A-Za-z0-9]+", verbose_name) if word]
    if words and words[0].upper() == "AA":
        words = words[1:]
    return "".join(word[0].upper() + word[1:] for word in words)


@dataclass(frozen=True)
class Rule:
    """One replacement: ``label`` for the report, ``compound`` for prose files."""

    label: str
    pattern: re.Pattern
    replacement: str
    compound: bool


def build_rules(src: Names, dst: Names) -> list[Rule]:
    """The replacements in the order they are applied (compound names first)."""
    alnum = "[A-Za-z0-9]"

    def bounded(word: str) -> re.Pattern:
        return re.compile(rf"(?<!{alnum}){re.escape(word)}(?!{alnum})")

    domains = "|".join(PROTECTED_DOMAINS)
    return [
        Rule("verbose name", bounded(src.verbose_name), dst.verbose_name, True),
        Rule("user agent", bounded(src.user_agent), dst.user_agent, True),
        Rule("app name", bounded(src.app_name), dst.app_name, True),
        Rule(
            "settings prefix",
            bounded(src.settings_prefix),
            dst.settings_prefix,
            False,
        ),
        # ``aaExampleSettings`` and ``ExampleConfig`` are renamed, a plural is not.
        Rule(
            "title",
            re.compile(rf"(?<![A-Z0-9]){re.escape(src.title)}(?![a-z0-9])"),
            dst.title,
            False,
        ),
        # ``example_task`` and ``example.models`` are renamed, ``examples`` and
        # ``example.com`` are not.
        Rule(
            "package",
            re.compile(
                rf"(?<!{alnum}){re.escape(src.package)}(?!{alnum})"
                rf"(?!\.(?:{domains})(?!{alnum}))"
            ),
            dst.package,
            False,
        ),
    ]


def replace_text(
    text: str, rules: list[Rule], compound_only: bool = False
) -> tuple[str, dict[str, int]]:
    """Apply the rules to ``text``; return the new text and the count per rule."""
    counts: dict[str, int] = {}
    for rule in rules:
        if compound_only and not rule.compound:
            continue
        text, count = rule.pattern.subn(lambda _m, r=rule: r.replacement, text)
        if count:
            counts[rule.label] = counts.get(rule.label, 0) + count
    return text, counts


@dataclass
class Report:
    """What the run changed."""

    replaced: dict[Path, dict[str, int]] = field(default_factory=dict)
    renamed: list[tuple[Path, Path]] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)
    skipped: list[Path] = field(default_factory=list)
    hints: list[str] = field(default_factory=list)


def git_ignored(root: Path) -> set[Path]:
    """The paths git ignores below ``root``; empty without git or a repository."""
    try:
        result = subprocess.run(
            [
                "git",
                "ls-files",
                "-z",
                "--others",
                "--ignored",
                "--exclude-standard",
                "--directory",
            ],
            cwd=root,
            capture_output=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return set()
    return {
        root / entry.decode("utf-8", errors="replace").rstrip("/")
        for entry in result.stdout.split(b"\0")
        if entry
    }


def collect_paths(root: Path) -> tuple[list[Path], list[Path]]:
    """All directories and files below ``root`` except skipped and ignored ones."""
    ignored = git_ignored(root)
    dirs: list[Path] = []
    files: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        base = Path(dirpath)
        dirnames[:] = sorted(
            name
            for name in dirnames
            if name not in SKIP_DIRS and base / name not in ignored
        )
        dirs.extend(base / name for name in dirnames)
        files.extend(
            base / name
            for name in sorted(filenames)
            if name not in SKIP_DIRS and base / name not in ignored
        )
    return dirs, files


def is_skipped_file(path: Path) -> bool:
    return any(fnmatch(path.name, pattern) for pattern in SKIP_FILE_PATTERNS)


def read_text(path: Path) -> str | None:
    """The content of a text file, ``None`` for binary or non-UTF-8 files."""
    data = path.read_bytes()
    if b"\0" in data:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def replace_in_files(
    root: Path, files: list[Path], rules: list[Rule], report: Report, dry_run: bool
) -> None:
    for path in files:
        if is_skipped_file(path):
            report.skipped.append(path.relative_to(root))
            continue
        text = read_text(path)
        if text is None:
            continue
        compound_only = path.relative_to(root).as_posix() in COMPOUND_ONLY_FILES
        new_text, counts = replace_text(text, rules, compound_only)
        if not counts:
            continue
        report.replaced[path.relative_to(root)] = counts
        if not dry_run:
            path.write_bytes(new_text.encode("utf-8"))


def rename_paths(
    root: Path,
    dirs: list[Path],
    files: list[Path],
    rules: list[Rule],
    report: Report,
    dry_run: bool,
) -> None:
    """Rename files and directories, deepest first, so parents move last."""
    for path in sorted(dirs + files, key=lambda p: len(p.parts), reverse=True):
        if path.is_dir() and path.name in SKIP_DIRS:
            continue
        new_name, counts = replace_text(path.name, rules)
        if not counts:
            continue
        target = path.with_name(new_name)
        if target.exists():
            raise InitAppError(f"Cannot rename {path} to {target}: target exists.")
        report.renamed.append((path.relative_to(root), target.relative_to(root)))
        if not dry_run:
            path.rename(target)


def set_version(init_file: Path, report: Report, dry_run: bool) -> None:
    text = init_file.read_text(encoding="utf-8")
    new_text, count = re.subn(
        r'^__version__ = "[^"]*"',
        f'__version__ = "{NEW_VERSION}"',
        text,
        count=1,
        flags=re.MULTILINE,
    )
    if not count:
        report.hints.append(f"No __version__ found in {init_file}.")
        return
    report.changed.append(f'__version__ = "{NEW_VERSION}" in {init_file.name}')
    if not dry_run:
        init_file.write_text(new_text, encoding="utf-8")


def reset_changelog(changelog: Path, report: Report, dry_run: bool) -> None:
    """Keep the head with an empty "In Development" section."""
    if not changelog.is_file():
        report.hints.append("No CHANGELOG.md found.")
        return
    lines = changelog.read_text(encoding="utf-8").splitlines(keepends=True)
    end = next((i for i, line in enumerate(lines) if line.strip() == "-->"), None)
    if end is None:
        end = next(
            (i - 1 for i, line in enumerate(lines) if re.match(r"^## \[\d", line)),
            len(lines) - 1,
        )
    head = "".join(lines[: end + 1])
    dev_link = next(
        (line for line in lines if line.lower().startswith("[in development]:")),
        "",
    )
    dev_link = re.sub(r"/compare/\S+", "/commits/master", dev_link.rstrip("\n"))
    new_text = head + "\n<!-- Your changes go here -->\n\n<!-- Links -->\n"
    if dev_link:
        new_text += f"\n{dev_link}\n"
    report.changed.append("CHANGELOG.md reset to an empty In Development section")
    if not dry_run:
        changelog.write_text(new_text, encoding="utf-8")


def drop_migrations(package_dir: Path, report: Report, dry_run: bool) -> None:
    migrations = sorted((package_dir / "migrations").glob("[0-9]*.py"))
    if not migrations:
        report.hints.append("No migrations to remove.")
    for path in migrations:
        report.removed.append(path.relative_to(package_dir.parent))
        if not dry_run:
            path.unlink()


def drop_template_override(app_py: Path, report: Report, dry_run: bool) -> None:
    """Remove the ``TEMPLATE ONLY`` ``permissions`` override from ``tests/testdata/app.py``."""
    if not app_py.is_file() or "TEMPLATE ONLY" not in app_py.read_text("utf-8"):
        report.hints.append(f"No TEMPLATE ONLY override in {app_py}.")
        return
    text = app_py.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    func = next(
        (
            node
            for node in ast.walk(ast.parse(text))
            if isinstance(node, ast.FunctionDef) and node.name == "permissions"
        ),
        None,
    )
    if func is None:
        report.hints.append(f"No permissions override found in {app_py}.")
        return
    start = min([node.lineno for node in func.decorator_list] + [func.lineno]) - 1
    while start > 0 and lines[start - 1].lstrip().startswith("#"):
        start -= 1
    end = func.end_lineno
    if end < len(lines) and not lines[end].strip():
        end += 1
    del lines[start:end]
    text = "".join(lines)
    # Imports that only the override used, and import groups that became empty.
    head, sep, tail = text.partition("\nclass ")
    for match in re.finditer(r"^from \S+ import (\w+)\n", head, flags=re.MULTILINE):
        if len(re.findall(rf"\b{match.group(1)}\b", text)) == 1:
            head = head.replace(match.group(0), "", 1)
    head = re.sub(r"^# [^\n]*\n\n", "", head, flags=re.MULTILINE)
    text = head + sep + tail
    ast.parse(text)
    report.changed.append(f"TEMPLATE ONLY override removed from {app_py.name}")
    if not dry_run:
        app_py.write_text(text, encoding="utf-8")


def read_source_names(root: Path) -> Names:
    config = configparser.ConfigParser(interpolation=None)
    config_file = root / CONFIG_FILE
    if not config.read(config_file, encoding="utf-8") or "General" not in config:
        raise InitAppError(f"{config_file} with a [General] section is required.")
    general = config["General"]
    try:
        return Names(general["package"], general["appname"], general["appname_verbose"])
    except KeyError as exc:
        raise InitAppError(f"{config_file} lacks [General] {exc}.") from exc


def run(
    root: Path,
    dst: Names,
    drop_migrations_: bool = False,
    drop_template_override_: bool = False,
    dry_run: bool = False,
) -> Report:
    """Rename the template under ``root`` to ``dst`` and return the report."""
    root = root.resolve()
    src = read_source_names(root)
    dst.validate()
    if dst.package == src.package:
        raise InitAppError(f"The package is already named {src.package!r}.")
    package_dir = root / src.package
    if not package_dir.is_dir():
        raise InitAppError(f"Package directory {package_dir} not found.")
    if (root / dst.package).exists():
        raise InitAppError(f"{root / dst.package} exists already.")

    report = Report()
    rules = build_rules(src, dst)
    dirs, files = collect_paths(root)
    replace_in_files(root, files, rules, report, dry_run)

    # Dry runs stop before the edits that build on the replaced text.
    set_version(package_dir / "__init__.py", report, dry_run)
    if not dry_run:
        reset_changelog(root / "CHANGELOG.md", report, dry_run)
    if drop_migrations_:
        drop_migrations(package_dir, report, dry_run)
    if drop_template_override_:
        drop_template_override(
            package_dir / "tests" / "testdata" / "app.py", report, dry_run
        )
        general_py = package_dir / "models" / "general.py"
        if general_py.is_file() and "abstract = True" in general_py.read_text("utf-8"):
            report.hints.append(
                "The General model is still abstract: remove `abstract = True` "
                "and `managed = False` in models/general.py and create a "
                "migration, otherwise the tests find no permissions."
            )
    rename_paths(root, dirs, files, rules, report, dry_run)

    preview = root / (src if dry_run else dst).package / "docs/images/preview-1.png"
    if preview.is_file():
        report.hints.append(
            f"{dst.package}/docs/images/preview-1.png is the preview image of "
            "the template; replace it with a screenshot of the new app."
        )
    report.hints.append(
        "Next: make tox-tests, make react-test, make react-lint, make react-build"
        + (", make migrations" if drop_migrations_ else "")
        + "."
    )
    return report


def print_report(src: Names, dst: Names, report: Report, dry_run: bool) -> None:
    prefix = "Would replace" if dry_run else "Replaced"
    print(
        f"{prefix} {src.package} -> {dst.package}, {src.title} -> {dst.title}, "
        f"{src.settings_prefix} -> {dst.settings_prefix}, "
        f"{src.app_name} -> {dst.app_name}, "
        f"{src.verbose_name} -> {dst.verbose_name}, "
        f"{src.user_agent} -> {dst.user_agent}"
    )
    total = sum(sum(counts.values()) for counts in report.replaced.values())
    print(f"  {total} replacements in {len(report.replaced)} files:")
    for path, counts in sorted(report.replaced.items()):
        detail = ", ".join(f"{label} {count}" for label, count in counts.items())
        print(f"    {path.as_posix()}: {detail}")
    if report.skipped:
        print(f"  skipped {len(report.skipped)} files (source maps, ESI specification)")
    prefix = "Would rename" if dry_run else "Renamed"
    print(f"{prefix} {len(report.renamed)} paths:")
    for old, new in report.renamed:
        print(f"    {old.as_posix()} -> {new.as_posix()}")
    if report.removed:
        prefix = "Would remove" if dry_run else "Removed"
        print(f"{prefix} {len(report.removed)} files:")
        for path in report.removed:
            print(f"    {path.as_posix()}")
    if report.changed:
        print("Changed:" if not dry_run else "Would change:")
        for note in report.changed:
            print(f"    {note}")
    if dry_run:
        print("    (CHANGELOG.md is reset in a real run)")
    for hint in report.hints:
        print(f"Hint: {hint}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Create a new Alliance Auth app from this template.",
        epilog="Example: %(prog)s --package ledger --app-name aa-ledger "
        '--verbose-name "AA Ledger"',
    )
    parser.add_argument("--package", required=True, help="Python package, e.g. ledger")
    parser.add_argument(
        "--app-name", required=True, help="repository and PyPI name, e.g. aa-ledger"
    )
    parser.add_argument(
        "--verbose-name", required=True, help='verbose name, e.g. "AA Ledger"'
    )
    parser.add_argument(
        "--drop-migrations",
        action="store_true",
        help="remove the migrations of the template (kept by default)",
    )
    parser.add_argument(
        "--drop-template-override",
        action="store_true",
        help="remove the TEMPLATE ONLY permissions override in tests/testdata/app.py "
        "(do this when you make the General model concrete)",
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="only report, change nothing"
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repository root (default: the parent of scripts/)",
    )
    args = parser.parse_args(argv)
    dst = Names(args.package, args.app_name, args.verbose_name)
    try:
        src = read_source_names(args.root)
        report = run(
            args.root,
            dst,
            drop_migrations_=args.drop_migrations,
            drop_template_override_=args.drop_template_override,
            dry_run=args.dry_run,
        )
    except InitAppError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    print_report(src, dst, report, args.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
